/** English `code` strings that have no Hindi entry yet (empty when the table is complete). */
export function missingCodesHi(): string[] {
  return CODES_BY_TOOL.flatMap((g) => g.codes).map((c) => c.code).filter((c) => !CODES_HI[c])
}

/** The code groups as the page shows them: English untouched, Hindi from the table (a source with no entry stays English). */
export function codesFor(locale: Locale): CodeGroup[] {
  if (locale !== 'hi') return CODES_BY_TOOL
  return CODES_BY_TOOL.map((g) => ({
    tool: g.tool,
    phase: g.phase,
    desc: DESC_HI[g.tool] ?? g.desc,
    codes: g.codes.map((c): CodeEntry => {
      const h = CODES_HI[c.code]
      if (!h) return c
      return { code: h.code ?? c.code, title: h.title, governs: h.governs, ...(h.caveat ? { caveat: h.caveat } : {}) }
    }),
  }))
}

type Json = Record<string, unknown>

/** The ItemList: English is `isCodesItemList(CODES_BY_TOOL)` from lib/seo/schema.ts, untouched; on /hi the same list in Hindi. */
export function isCodesItemListHi(): Json {
  const seen = new Map<string, { code: string; title: string; governs: string; caveat?: string; tools: string[] }>()
  const english = CODES_BY_TOOL
  const hindi = codesFor('hi')
  english.forEach((g, gi) => {
    g.codes.forEach((c, ci) => {
      const h = hindi[gi].codes[ci]
      const hit = seen.get(c.code)
      if (hit) {
        if (!hit.tools.includes(g.tool)) hit.tools.push(g.tool)
      } else {
        seen.set(c.code, { code: h.code, title: h.title, governs: h.governs, caveat: h.caveat, tools: [g.tool] })
      }
    })
  })
  const items = [...seen.values()]
  return {
    '@type': 'ItemList',
    name: 'NirmanShastra में प्रयुक्त IS कोड',
    numberOfItems: items.length,
    itemListElement: items.map((v, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      item: {
        '@type': 'CreativeWork',
        name: v.code,
        alternateName: v.title,
        description: `${v.governs}${v.caveat ? ` सीमा: ${v.caveat}` : ''} इनमें इस्तेमाल: ${v.tools.join(', ')}।`,
        publisher: { '@type': 'Organization', name: 'Bureau of Indian Standards' },
      },
    })),
  }
}
